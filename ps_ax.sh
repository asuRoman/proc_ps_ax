#!/bin/bash
# Задание: описание процессов из /proc

#  для красоты отображения делаем разметку столбцов
printf "%7s %7s %-5s %s\n" "PID" "PPID" "STATE" "COMMAND"

#создаем цикл по каталогам /proc
for dir in /proc/[0-9]*; do
    pid=${dir#/proc/}

    # Процесс мог завершиться между listdir и чтением — проверяем доступность
    [ -r "$dir/stat" ] || continue

    # читаем файл с помощью < без использования cat и тд, READ чтобы работало не только в BASH
    # -r не итерпритировать обратные слэши
    IFS= read -r line < "$dir/stat" || continue

    # command между первой ( и последней )  (имя может содержать пробелы и скобки)
    command=${line#*(}      # убрать всё до первой (
    command=${command%)*}      # убрать от последней ) до конца

    # всё после последнего ) — это state ppid
    rest=${line##*\)}    # убрать всё до последней )
    rest=${rest# }       # убрать пробел

    state=${rest%% *}    # первое слово = состояние
    rest=${rest#* }      # отрезать state
    ppid=${rest%% *}     # второе слово = ppid

    # команда запуска (аргументы разделены \0)
    cmd=""
    [ -r "$dir/cmdline" ] && cmd=$(tr '\0' ' ' < "$dir/cmdline" 2>/dev/null | sed 's/ *$//')

    # у ядерных потоков и зомби cmdline пустой — показываем имя в скобках
    [ -z "$cmd" ] && cmd="[$command]"

    printf "%7s %7s %-5s %s\n" "$pid" "$ppid" "$state" "$cmd"

#  сортируем, чтобы шло 1,2,5,10, а не 1,10,2....
done | sort -n